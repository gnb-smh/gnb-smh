def cover(meta):
    return f"""
<section class="cover">
  <div class="title">
    <div class="small">CODE AUDIT REPORT</div>
    <h1>GnB-SMH Source Code Audit</h1>
    <div class="subtitle"><b>Ultra-deep security and consensus-consistency review,<br>with a comparative analysis against Bitcoin Core</b></div>
    <div class="subtitle" style="font-size:10.5pt;margin-top:10pt">GnB (G&ouml;del and Bell) post-quantum proof-of-work BlockDAG &middot; code-only assessment &middot; 14 October 2026</div>
  </div>
  <div class="meta">
    {table(["Item", "Value"], meta, cls="compact", widths=["32%", "68%"])}
  </div>
</section>"""


def toc(sections):
    items = "".join(f'<li><a href="#{sid}">{esc(title)}</a></li>' for sid, title in sections)
    return f'<h2 id="toc">Contents</h2><div class="toc"><ul>{items}</ul></div>'


def render_findings(findings):
    out = []
    for f in findings:
        refs = f.get("refs", [])
        loc = "; ".join(refs)
        parts = [
            f'<div class="finding"><div class="fh">{sev_badge(f["severity"])} '
            f'{esc(f["id"])} &mdash; {rich(f["title"])}</div><div class="fb">',
            f'<div class="loc">Location: {rich(loc)} &middot; Area: {esc(f["area"])} '
            f'&middot; Evidence: {esc(f["evidence"])}</div>',
            f'<p>{rich(f["description"])}</p>',
        ]
        if f.get("scenario"):
            parts.append(f'<p><b>Failure scenario.</b> {rich(f["scenario"])}</p>')
        if f.get("btc"):
            parts.append(f'<p><b>Bitcoin Core.</b> {rich(f["btc"])}</p>')
        parts.append(f'<p><b>Recommendation.</b> {rich(f["recommendation"])}</p></div></div>')
        out.append("".join(parts))
    return "".join(out)


def score_bar(v, btc=False):
    return f'<div class="bar{" btc" if btc else ""}"><span style="width:{v * 10:.0f}%"></span></div>'


def main():
    os.makedirs(OUT, exist_ok=True)
    findings = load("findings.json")
    findings.sort(key=lambda f: (SEV_ORDER.index(f["severity"]), f["id"]))
    score = load("scorecard.json")
    comps = load("components.json")
    inv = load("test_inventory.json")
    metrics = load("metrics.json")
    narrative = load("narrative.json")

    sections = narrative["sections"]  # list of [id, title]
    body = [cover(narrative["cover_meta"]), toc(sections)]

    for sec in narrative["blocks"]:
        sid, title, kind = sec["id"], sec["title"], sec["kind"]
        cls = ' class="pb"' if sec.get("page_break") else ""
        body.append(f'<h2 id="{sid}"{cls}>{esc(title)}</h2>')
        for blk in sec["content"]:
            t = blk["t"]
            if t == "p":
                body.append(para(*blk["v"]))
            elif t == "h3":
                body.append(f"<h3>{rich(blk['v'])}</h3>")
            elif t == "h4":
                body.append(f"<h4>{rich(blk['v'])}</h4>")
            elif t == "ul":
                body.append(bullets(blk["v"]))
            elif t == "box":
                body.append(f'<div class="box {blk.get("cls", "")}">{para(*blk["v"])}</div>')
            elif t == "table":
                body.append(table(blk["h"], blk["rows"], cls=blk.get("cls", ""), widths=blk.get("w")))
            elif t == "findings":
                body.append(render_findings(findings))
            elif t == "findings_summary":
                counts = {s: sum(1 for f in findings if f["severity"] == s) for s in SEV_ORDER}
                rows = [[s, str(counts[s])] for s in SEV_ORDER] + [["Total", str(len(findings))]]
                body.append(table(["Severity", "Count"], rows, cls="compact", widths=["70%", "30%"]))
                rows = [
                    [sev_badge(f["severity"]), esc(f["id"]), rich(f["title"]), esc(f["area"])]
                    for f in findings
                ]
                body.append(table(["Sev.", "ID", "Title", "Area"], rows, cls="compact",
                                  widths=["9%", "11%", "62%", "18%"], raw_cols=(0, 1, 2, 3)))
            elif t == "scorebig":
                body.append(
                    f'<div class="scorebig"><div><div class="v">{score["gnb_total"]:.1f} / 10</div>'
                    f'<div class="l">GnB-SMH (commit 125e9e5)</div></div>'
                    f'<div><div class="v">{score["btc_total"]:.1f} / 10</div>'
                    f'<div class="l">Bitcoin Core (master f13ae51)</div></div></div>'
                )
            elif t == "scorecard":
                rows = []
                for c in score["categories"]:
                    rows.append([
                        rich(c["name"]), f'{c["weight"]}%',
                        f'{c["gnb"]:.1f}' + score_bar(c["gnb"]),
                        f'{c["btc"]:.1f}' + score_bar(c["btc"], True),
                        rich(c["why"]),
                    ])
                rows.append([
                    "<b>Weighted total</b>", "100%", f'<b>{score["gnb_total"]:.2f}</b>',
                    f'<b>{score["btc_total"]:.2f}</b>', rich(score["total_note"]),
                ])
                body.append(table(["Category", "Weight", "GnB", "Bitcoin Core", "Basis (code evidence)"],
                                  rows, cls="compact", widths=["19%", "7%", "10%", "10%", "54%"],
                                  raw_cols=(0, 1, 2, 3, 4)))
            elif t == "components":
                for c in comps:
                    body.append(f"<h3>{rich(c['title'])}</h3>")
                    body.append(table(["", "GnB-SMH", "Bitcoin Core"], c["rows"], cls="compact",
                                      widths=["18%", "41%", "41%"]))
                    if c.get("note"):
                        body.append(para(c["note"]))
            elif t == "metrics":
                m = metrics[blk["key"]]
                body.append(table(m["headers"], m["rows"], cls="compact", widths=m.get("w")))
            elif t == "inventory":
                kind_f = blk["kind"]
                rows = []
                for r in inv:
                    if r["kind"] != kind_f:
                        continue
                    rows.append([f'`{r["path"]}`', str(r["tests"]), r.get("tags", ""), r.get("purpose", r.get("doc", ""))])
                body.append(table(["Module", "Tests", "Kind", "Security / consistency property checked"],
                                  rows, cls="compact", widths=["37%", "6%", "11%", "46%"]))
            else:
                raise SystemExit(f"unknown block type {t}")

    doc = (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        "<title>GnB-SMH Code Audit</title>"
        f"<style>{CSS}</style></head><body>" + "".join(body) + "</body></html>"
    )
    path = os.path.join(OUT, "report.html")
    with open(path, "w", encoding="utf-8") as f:
        f.write(doc)
    print("wrote", path)


if __name__ == "__main__":
    sys.exit(main())
