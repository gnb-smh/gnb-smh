def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return json.load(f)


def esc(s):
    return html.escape(str(s), quote=False)


def rich(s):
    """Escape, then allow `code` spans, **bold** and *italic*."""
    s = esc(s)
    out, code, bold, ital = [], False, False, False
    i = 0
    while i < len(s):
        if s[i] == "`":
            out.append("</code>" if code else "<code>")
            code = not code
            i += 1
        elif s.startswith("**", i) and not code:
            out.append("</b>" if bold else "<b>")
            bold = not bold
            i += 2
        elif s[i] == "*" and not code and (ital or (i + 1 < len(s) and s[i + 1].isalpha())):
            out.append("</i>" if ital else "<i>")
            ital = not ital
            i += 1
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def para(*texts):
    return "".join(f"<p>{rich(t)}</p>" for t in texts)


def bullets(items):
    return "<ul>" + "".join(f"<li>{rich(i)}</li>" for i in items) + "</ul>"


def table(headers, rows, cls="", widths=None, raw_cols=()):
    h = "".join(
        f'<th style="width:{widths[i]}">{esc(x)}</th>' if widths else f"<th>{esc(x)}</th>"
        for i, x in enumerate(headers)
    )
    body = []
    for r in rows:
        cells = []
        for i, c in enumerate(r):
            cells.append(f"<td>{c if i in raw_cols else rich(c)}</td>")
        body.append("<tr>" + "".join(cells) + "</tr>")
    return f'<table class="{cls}"><thead><tr>{h}</tr></thead><tbody>{"".join(body)}</tbody></table>'


