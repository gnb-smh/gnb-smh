"""Assemble the GnB-SMH audit report (HTML) from the audit data files.

    python3 audit/report/build_report.py            # writes audit/report/out/report.html
    node audit/report/print_pdf.cjs audit/report/out/report.html \
         audit/GnB-SMH-Code-Audit-2026-10-14.pdf

Inputs (all in audit/report/inputs/):
    findings.json        severity-ranked findings
    scorecard.json       weighted category scores, GnB vs Bitcoin Core
    components.json      per-component comparison narrative
    test_inventory.json  every GnB test module (generated by the inventory script)
    metrics.json         code-size, hazard and Bitcoin Core metrics
Standard library only.
"""

import html
